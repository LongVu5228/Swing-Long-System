"""
Blind flag trainer. Emits htf_trainer.pine (blacks out every bar after a flag's setup_confirmed
date) and the shuffled queue htf_trainer_queue.csv you fill in: pattern, r1_date (YYYYMMDD of
the bar whose high is R1), optional clean (1 clean / 2 borderline / 3 messy) and notes.
score_trainer.py then compares your answers with the original labels and the backtest.

All hand-labeled flags are in the queue (not only red), so the pattern answer is genuinely
blind. Per ticker the flags are numbered 1..n in date order ("Flag # on this ticker" input);
tickers come in a fixed random order (seed 42); each flag gets a random A/B half.
htf_trainer_key.csv maps train_id back to flag_no -- don't open it while grading.

Data per ticker: ";AA:id,confYYYYMMDD/id,confYYYYMMDD". Pine string constraints as in
generate_scanner_days.py (big literals only in plain top-level statements).

    python generate_trainer.py                 # all labeled flags
    python generate_trainer.py --patterns red  # Red HTF + Big Red Flag only
    python generate_trainer.py --force         # overwrite an existing queue (loses answers!)
"""
import argparse
import os

import numpy as np
import pandas as pd

import quick_backtest_chosen_one as qb

HERE = os.path.dirname(os.path.abspath(__file__))
TRUTH = os.path.join(HERE, "htf_pattern_truth.csv")
RED = ["Red HTF", "Big Red Flag"]
PIECE = 3000


def flags(patterns: str) -> pd.DataFrame:
    m = qb.read_master()
    m = m[m.flag_no > 0].merge(pd.read_csv(TRUTH)[["ticker", "flag_no", "truth"]], on=["ticker", "flag_no"])
    if patterns == "red":
        m = m[m.truth.isin(RED)]
    m = m.dropna(subset=["setup_confirmed"])
    return m.sort_values(["ticker", "setup_confirmed", "flag_no"]).reset_index(drop=True)


def build(m: pd.DataFrame, seed: int):
    rng = np.random.default_rng(seed)
    m = m.copy()
    m["k"] = m.groupby("ticker").cumcount() + 1
    order = {t: i for i, t in enumerate(rng.permutation(m.ticker.unique()))}
    m = m.assign(o=m.ticker.map(order)).sort_values(["o", "k"]).drop(columns="o").reset_index(drop=True)
    m["train_id"] = np.arange(1, len(m) + 1)
    m["half"] = rng.choice(["A", "B"], size=len(m))
    data = "".join(f";{t}:" + "/".join(f"{r.train_id},{int(r.setup_confirmed)}" for r in g.itertuples())
                   for t, g in m.sort_values(["ticker", "k"]).groupby("ticker", sort=True))
    return m, data


def pieces(data: str) -> list:
    out, cur = [], ""
    for s in [";" + s for s in data.split(";") if s]:
        if cur and len(cur) + len(s) > PIECE:
            out.append(cur)
            cur = ""
        cur += s
    return out + ([cur] if cur else [])


def pine(title: str, data: str, n_flags: int) -> str:
    ps = pieces(data)
    decls = "\n".join(f'D{i} = "{p}"' for i, p in enumerate(ps))
    finds = "\n".join(f"s{i} = cut(D{i}, key)" for i in range(len(ps)))
    joined = " + ".join(f"s{i}" for i in range(len(ps)))
    return f'''//@version=6
// {title} -- GENERATED by generate_trainer.py; edit that, not this. {n_flags} flags.
// Blacks out every bar after the chosen flag's confirmation date. Daily chart. Hide your
// recorder / flag-box indicators first; untick "Black out" to reveal.
indicator("{title}", overlay = true)

{decls}

pick = input.int(1, "Flag # on this ticker", minval = 1)
blackout = input.bool(true, "Black out after confirmation")
coverCol = input.color(color.black, "Cover color")

cut(string src, string k) =>
    p = str.pos(src, k)
    rest = na(p) ? "" : str.substring(src, p + str.length(k))
    q = str.pos(rest, ";")
    na(q) ? rest : str.substring(rest, 0, q)

key = ";" + syminfo.ticker + ":"
{finds}
seg = {joined}

var int[] ids = array.new<int>()
var int[] confs = array.new<int>()
var bool parsed = false
while not parsed
    parsed := true
    fs = str.split(seg, "/")
    j = 0
    while j < array.size(fs)
        f = str.split(array.get(fs, j), ",")
        if array.size(f) >= 2
            array.push(ids, int(str.tonumber(array.get(f, 0))))
            array.push(confs, int(str.tonumber(array.get(f, 1))))
        j += 1

n = array.size(confs)
has = n > 0 and pick <= n
conf = has ? array.get(confs, pick - 1) : 0
tid = has ? array.get(ids, pick - 1) : 0
d = year * 10000 + month * 100 + dayofmonth
cover = has and blackout and d > conf

// Indicators draw above the main series, so solid candles in the cover color hide the real ones.
plotcandle(cover ? open : na, cover ? high : na, cover ? low : na, cover ? close : na, "Cover", color = coverCol, wickcolor = coverCol, bordercolor = coverCol, display = display.pane)
bgcolor(cover ? coverCol : na)

var table panel = table.new(position.top_right, 1, 2, bgcolor = color.new(color.gray, 20), border_width = 0)
if barstate.islast
    if n == 0
        table.cell(panel, 0, 0, syminfo.ticker + ": not in trainer set", text_color = color.white)
    else if pick > n
        table.cell(panel, 0, 0, syminfo.ticker + ": only " + str.tostring(n) + " flag(s)", text_color = color.red)
    else
        table.cell(panel, 0, 0, "Train #" + str.tostring(tid), text_color = color.white)
        table.cell(panel, 0, 1, "Flag " + str.tostring(pick) + " of " + str.tostring(n), text_color = color.white)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--patterns", choices=["red", "all"], default="all")
    ap.add_argument("--out", default="htf_trainer")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    m, data = build(flags(a.patterns), a.seed)
    with open(os.path.join(HERE, a.out + ".pine"), "w", encoding="utf-8") as fh:
        fh.write(pine("HTF Trainer", data, len(m)))
    q = os.path.join(HERE, a.out + "_queue.csv")
    if os.path.exists(q) and not a.force:
        print(f"queue exists, left alone (answers safe): {q}")
    else:
        m.assign(pattern="", r1_date="", clean="", notes="") \
            [["train_id", "ticker", "k", "half", "pattern", "r1_date", "clean", "notes"]] \
            .rename(columns={"k": "flag_on_ticker"}).to_csv(q, index=False)
        print(f"queue: {q}")
    m[["train_id", "ticker", "flag_no", "k", "half", "truth", "setup_confirmed", "r1_source_bar", "r1_price"]] \
        .to_csv(os.path.join(HERE, a.out + "_key.csv"), index=False)
    print(f"{len(m)} flags, {m.ticker.nunique()} tickers, {len(pieces(data))} pieces, "
          f"{len(data) / 1024:.1f} KB -> {a.out}.pine")


if __name__ == "__main__":
    main()
